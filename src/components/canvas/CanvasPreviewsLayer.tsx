/**
 * @file CanvasPreviewsLayer.tsx
 * @description Real-time interactive feedback layer for in-progress vector drawing.
 * Renders dashed geometric snapping guides and live freehand stroke previews
 * while the user is actively dragging or drawing on the canvas.
 */

import React from 'react';
import { Point, ToolType } from '../../types/whiteboard';
import { SnappedShapeResult } from '../../utils/shapeDetection';
import { renderPointsToSvgPath } from '../../utils/canvasGeometry';

/**
 * Properties for CanvasPreviewsLayer.
 */
interface CanvasPreviewsLayerProps {
  /** Whether the pointer is currently down and drawing */
  isDrawing: boolean;
  /** Active stroke points accumulated during current drag */
  currentStroke: Point[];
  /** Snapped geometric shape preview generated by heuristic detector */
  currentShapePreview: SnappedShapeResult | null;
  /** Active whiteboard tool */
  currentTool: ToolType;
  /** Primary stroke color */
  color: string;
  /** Active stroke width in canvas pixels */
  strokeWidth: number;
}

/**
 * CanvasPreviewsLayer renders ephemeral drawing artifacts:
 * - Real-time bezier curve path of the currently drawn stroke
 * - Semi-transparent dashed outlines showing auto-snapped shape previews
 */
export const CanvasPreviewsLayer: React.FC<CanvasPreviewsLayerProps> = ({
  isDrawing,
  currentStroke,
  currentShapePreview,
  currentTool,
  color,
  strokeWidth,
}) => {
  if (!isDrawing) return null;

  return (
    <>
      {/* Live Freehand Stroke Preview */}
      {currentStroke.length > 1 && (
        <path
          data-testid="drawing-stroke-preview"
          d={renderPointsToSvgPath(currentStroke)}
          fill="none"
          stroke={color}
          strokeWidth={currentTool === 'highlighter' ? strokeWidth * 3.5 : strokeWidth}
          strokeLinecap="round"
          strokeLinejoin="round"
          opacity={currentTool === 'highlighter' ? 0.35 : 1}
        />
      )}

      {/* Live Geometric Snapping Preview (rendered with dashed border) */}
      {currentShapePreview && (
        <g opacity={0.85} data-testid="shape-preview">
          {currentShapePreview.shapeType === 'line' && (
            <line
              x1={currentShapePreview.x}
              y1={currentShapePreview.y}
              x2={currentShapePreview.x2}
              y2={currentShapePreview.y2}
              stroke={color}
              strokeWidth={strokeWidth}
              strokeLinecap="round"
              strokeDasharray="4 4"
            />
          )}
          {currentShapePreview.shapeType === 'arrow' && (
            <line
              x1={currentShapePreview.x}
              y1={currentShapePreview.y}
              x2={currentShapePreview.x2}
              y2={currentShapePreview.y2}
              stroke={color}
              strokeWidth={strokeWidth}
              strokeLinecap="round"
              strokeDasharray="4 4"
            />
          )}
          {currentShapePreview.shapeType === 'rectangle' && (
            <rect
              x={currentShapePreview.x}
              y={currentShapePreview.y}
              width={currentShapePreview.width}
              height={currentShapePreview.height}
              fill="transparent"
              stroke={color}
              strokeWidth={strokeWidth}
              strokeDasharray="4 4"
              rx={4}
            />
          )}
          {currentShapePreview.shapeType === 'circle' && (
            <ellipse
              cx={currentShapePreview.x + currentShapePreview.width / 2}
              cy={currentShapePreview.y + currentShapePreview.height / 2}
              rx={Math.abs(currentShapePreview.width / 2)}
              ry={Math.abs(currentShapePreview.height / 2)}
              fill="transparent"
              stroke={color}
              strokeWidth={strokeWidth}
              strokeDasharray="4 4"
            />
          )}
          {currentShapePreview.shapeType === 'triangle' && (
            <polygon
              points={`${currentShapePreview.x + currentShapePreview.width / 2},${currentShapePreview.y} ${currentShapePreview.x + currentShapePreview.width},${currentShapePreview.y + currentShapePreview.height} ${currentShapePreview.x},${currentShapePreview.y + currentShapePreview.height}`}
              fill="transparent"
              stroke={color}
              strokeWidth={strokeWidth}
              strokeDasharray="4 4"
              strokeLinejoin="round"
            />
          )}
        </g>
      )}
    </>
  );
};
